CREATE OR REPLACE VIEW DE_PORTFOLIO_DB.ANALYTICS.CUSTOMER_SUMMARY AS
SELECT
    STATE,
    CUSTOMER_STATUS,
    COUNT(*) AS CUSTOMER_COUNT
FROM DE_PORTFOLIO_DB.ANALYTICS.CLEAN_CUSTOMERS
GROUP BY STATE, CUSTOMER_STATUS;

-- Expected output:
-- CA | ACTIVE   | 3
-- TX | INACTIVE | 1
SELECT *
FROM DE_PORTFOLIO_DB.ANALYTICS.CUSTOMER_SUMMARY
ORDER BY STATE, CUSTOMER_STATUS;
